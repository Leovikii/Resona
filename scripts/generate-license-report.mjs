import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const workspace = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cargoCommand = process.platform === "win32" ? "cargo.exe" : "cargo";
const cargo = spawnSync(
  cargoCommand,
  ["metadata", "--format-version", "1", "--locked", "--manifest-path", "src-tauri/Cargo.toml"],
  { cwd: workspace, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
);

if (cargo.status !== 0) {
  throw new Error(cargo.error?.message || cargo.stderr || "cargo metadata failed");
}

const metadata = JSON.parse(cargo.stdout);
const rustPackages = metadata.packages
  .filter((pkg) => pkg.source)
  .map((pkg) => ({ name: pkg.name, version: pkg.version, license: pkg.license ?? "UNKNOWN" }))
  .sort(comparePackages);

const packageLock = JSON.parse(readFileSync(resolve(workspace, "package-lock.json"), "utf8"));
const npmPackages = Object.entries(packageLock.packages)
  .filter(([path]) => path)
  .map(([path, pkg]) => ({
    name: path.split("node_modules/").at(-1),
    version: pkg.version,
    license: pkg.license ?? "UNKNOWN",
  }))
  .filter(uniquePackage())
  .sort(comparePackages);

const unknown = [...rustPackages, ...npmPackages].filter((pkg) => pkg.license === "UNKNOWN");
const lines = [
  "# Third-party dependency licenses",
  "",
  "Generated by `npm run licenses` from `Cargo.lock`, Cargo package metadata, and `package-lock.json`.",
  "This inventory is an engineering aid, not legal advice. Release review must also include bundled binaries and assets.",
  "",
  `- Rust packages: ${rustPackages.length}`,
  `- npm packages: ${npmPackages.length}`,
  `- Unknown license declarations: ${unknown.length}`,
  "",
  "## Rust",
  "",
  "| Package | Version | Declared license |",
  "| --- | --- | --- |",
  ...rustPackages.map(tableRow),
  "",
  "## npm",
  "",
  "| Package | Version | Declared license |",
  "| --- | --- | --- |",
  ...npmPackages.map(tableRow),
  "",
];

writeFileSync(resolve(workspace, "docs/THIRD_PARTY_LICENSES.md"), lines.join("\n"), "utf8");
if (unknown.length > 0) {
  throw new Error(`license metadata missing for: ${unknown.map((pkg) => pkg.name).join(", ")}`);
}

function comparePackages(left, right) {
  return left.name.localeCompare(right.name) || left.version.localeCompare(right.version);
}

function tableRow(pkg) {
  return `| ${pkg.name} | ${pkg.version} | ${pkg.license.replaceAll("|", "\\|")} |`;
}

function uniquePackage() {
  const seen = new Set();
  return (pkg) => {
    const key = `${pkg.name}@${pkg.version}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  };
}
